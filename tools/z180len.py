# dlzka instrukcie Z80/Z180
M = [1]*256
for o,l in {0x01:3,0x06:2,0x0e:2,0x10:2,0x11:3,0x16:2,0x18:2,0x1e:2,0x20:2,0x21:3,
            0x22:3,0x26:2,0x28:2,0x2a:3,0x2e:2,0x30:2,0x31:3,0x32:3,0x36:2,0x38:2,
            0x3a:3,0x3e:2}.items(): M[o]=l
for o in (0xc2,0xc3,0xc4,0xca,0xcc,0xcd,0xd2,0xd4,0xda,0xdc,0xe2,0xe4,0xea,0xec,
          0xf2,0xf4,0xfa,0xfc): M[o]=3
for o in (0xc6,0xce,0xd6,0xde,0xe6,0xee,0xf6,0xfe,0xd3,0xdb): M[o]=2
IDX = set([0x34,0x35,0x46,0x4e,0x56,0x5e,0x66,0x6e,0x7e,0x86,0x8e,0x96,0x9e,
           0xa6,0xae,0xb6,0xbe]) | set(range(0x70,0x78)) - {0x76}
ED4 = {0x43,0x4b,0x53,0x5b,0x63,0x6b,0x73,0x7b}

def ilen(d,p):
    op=d[p]
    if op==0xcb: return 2
    if op==0xed:
        b=d[p+1]
        if (b&0xc7) in (0x00,0x01) and b<0x40: return 3
        if b in (0x64,0x74): return 3
        if b in ED4: return 4
        return 2
    if op in (0xdd,0xfd):
        b=d[p+1]
        if b==0xcb: return 4
        if b==0x36: return 4
        if b in (0x21,0x22,0x2a): return 4
        if b in IDX: return 3
        return 1+ilen(d,p+1)
    return M[op]
